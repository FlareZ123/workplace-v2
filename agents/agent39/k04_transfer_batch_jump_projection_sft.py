#!/usr/bin/env python3
"""Source-bounded K04 test of transfer-volume jumps in the conditional p951 MT model.

Run from the repository checkout:
    python agents/agent39/k04_transfer_batch_jump_projection_sft.py

This is a falsification/projection experiment, not a claim that transfer payload
bytes were generated by MT19937. It tests the source-derived 2^18, 2^21, and
2^22 word-count hypotheses and a dry-run-zero alternative.
"""
from __future__ import annotations

import collections
import gc
import hashlib
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "agents" / "agent49"))
import k04_p951_symbolic_basis as mt  # noqa: E402

DEGREE = 19937
MASK32 = 0xFFFFFFFF
MAG = 0x9908B0DF
TRANSFER_HASH = "32970ad4431a9d610cc12dcca2813f39dd8fd2e396f9e748dc94b5932cb69adf"


def temper_word(x: int) -> int:
    x ^= x >> 11
    x ^= (x << 7) & 0x9D2C5680
    x ^= (x << 15) & 0xEFC60000
    x ^= x >> 18
    return x & MASK32


def concrete_bit_stream(seed: int, bit: int, count: int) -> list[int]:
    rng = random.Random(seed)
    state = [rng.getrandbits(32) for _ in range(624)]
    out = []
    for i in range(count):
        a = state[i % 624]
        b = state[(i + 1) % 624]
        c = state[(i + 397) % 624]
        y = c ^ ((((a & 0x80000000) | (b & 0x7FFFFFFF)) >> 1))
        if b & 1:
            y ^= MAG
        y &= MASK32
        state[i % 624] = y
        out.append((temper_word(y) >> bit) & 1)
    return out


def berlekamp_massey(bits: list[int]) -> tuple[int, int]:
    """Return linear complexity and the BM connection polynomial."""
    C = B = 1
    length = 0
    last_update = -1
    reversed_prefix = 0
    for n, bit in enumerate(bits):
        reversed_prefix = (reversed_prefix << 1) | int(bit)
        discrepancy = (C & reversed_prefix).bit_count() & 1
        if discrepancy:
            old_C = C
            C ^= B << (n - last_update)
            if 2 * length <= n:
                length = n + 1 - length
                B = old_C
                last_update = n
    return length, C


def reverse_bits(value: int, width: int) -> int:
    out = 0
    for i in range(width):
        out = (out << 1) | ((value >> i) & 1)
    return out


def make_square_table() -> list[int]:
    return [
        sum(1 << (2 * i) for i in range(8) if (value >> i) & 1)
        for value in range(256)
    ]


def poly_square_mod(value: int, modulus: int, square_table: list[int]) -> int:
    """Square a GF(2) polynomial and reduce modulo a degree-19937 polynomial."""
    out = 0
    shift = 0
    x = value
    while x:
        out |= square_table[x & 0xFF] << shift
        x >>= 8
        shift += 16
    while out.bit_length() - 1 >= DEGREE:
        offset = out.bit_length() - 1 - DEGREE
        out ^= modulus << offset
    return out


def mul_x_mod(value: int, modulus: int) -> int:
    if (value >> (DEGREE - 1)) & 1:
        return (value << 1) ^ modulus
    return value << 1


def x_power_mod(exponent: int, modulus: int, square_table: list[int]) -> int:
    """Compute x^exponent mod modulus for nonnegative exponent."""
    if exponent == 0:
        return 1
    k = exponent.bit_length() - 1
    multiplier = exponent >> k
    offset = exponent - (multiplier << k)
    value = 1 << multiplier
    for _ in range(k):
        value = poly_square_mod(value, modulus, square_table)
    for _ in range(offset):
        value = mul_x_mod(value, modulus)
    return value


def coefficients_for_burst(start_stage: int, modulus: int,
                            square_table: list[int]) -> list[int]:
    # The first post-twist output is conceptual stage -476.
    exponent = start_stage + 476
    assert exponent >= 0
    value = x_power_mod(exponent, modulus, square_table)
    coefficients = []
    for _ in range(16):
        coefficients.append(value)
        value = mul_x_mod(value, modulus)
    return coefficients


def symbolic_output_bit_forms(bit: int) -> list[int]:
    """Forms for one tempered output bit at stages -476 onward."""
    ring = [[1 << (32 * i + j) for j in range(32)] for i in range(624)]
    forms = []
    for n in range(DEGREE):
        a = ring[n % 624]
        b = ring[(n + 1) % 624]
        c = ring[(n + 397) % 624]
        new = [
            c[j]
            ^ (a[31] if j == 30 else (b[j + 1] if j < 30 else 0))
            ^ (b[0] if (MAG >> j) & 1 else 0)
            for j in range(32)
        ]
        ring[n % 624] = new
        forms.append(mt.temper(new)[bit])
    return forms


def combine_form(forms: list[int], coefficient: int) -> int:
    out = 0
    while coefficient:
        low = coefficient & -coefficient
        out ^= forms[low.bit_length() - 1]
        coefficient ^= low
    return out


def clone_basis(source):
    out = mt.Basis()
    out.rows = dict(source.rows)
    out.rank = source.rank
    return out


def transfer_rows(audit: list[dict], transfer: str) -> list[dict]:
    rows = sorted(
        (row for row in audit
         if row.get("kind") == "CHUNK" and row.get("transfer") == transfer),
        key=lambda row: (row["seq"], row["attempt"]),
    )
    assert len(rows) == 16, (transfer, len(rows))
    assert [(r["seq"], r["attempt"]) for r in rows] == [
        (seq, attempt) for seq in range(8) for attempt in (1, 2)
    ]
    assert all(int(row["bytes"]) == 1_048_576 for row in rows)
    return rows


def concrete_output_at(seed: int, index: int) -> int:
    rng = random.Random(seed)
    state = [rng.getrandbits(32) for _ in range(624)]
    for i in range(index + 1):
        a = state[i % 624]
        b = state[(i + 1) % 624]
        c = state[(i + 397) % 624]
        y = c ^ ((((a & 0x80000000) | (b & 0x7FFFFFFF)) >> 1))
        if b & 1:
            y ^= MAG
        y &= MASK32
        state[i % 624] = y
    return temper_word(y)


def main() -> None:
    audit_path = ROOT / "resources" / "evidence" / "transfers" / "transfer-audit.jsonl"
    raw_audit = audit_path.read_bytes()
    assert hashlib.sha256(raw_audit).hexdigest() == TRANSFER_HASH
    audit = [json.loads(line) for line in raw_audit.splitlines() if line.strip()]

    tags = ("AX-7778", "AX-7781", "AX-7782", "AX-7783")
    rows = {tag: transfer_rows(audit, tag) for tag in tags}
    values = {
        tag: [
            int.from_bytes(bytes.fromhex(row["checkpoint"]), "little")
            for row in rows[tag]
        ]
        for tag in tags
    }

    # Rebuild the existing source-only printer basis and preserve its target.
    basis, symbols = mt.source(ROOT)
    assert basis.rank == 15365
    target_forms = [
        form
        for stage in range(951, 955)
        for form in mt.temper(mt.get(symbols, stage))
    ]
    assert len(target_forms) == 128

    # Reproduce the AX-7778 bridge at stages -157..-142. Checkpoint hex is
    # interpreted little-endian and constrains the upper 16 tempered bits.
    ax7778_preinsert_fixed = 0
    for index, checkpoint in enumerate(values["AX-7778"]):
        forms = mt.temper(mt.get(symbols, -157 + index))
        for bit in range(16):
            form = forms[16 + bit]
            if basis.predict(form) is not None:
                ax7778_preinsert_fixed += 1
            basis.insert(form, (checkpoint >> bit) & 1)
    assert basis.rank == 15495
    assert ax7778_preinsert_fixed == 126
    assert sum(basis.predict(form) is not None for form in target_forms) == 0
    del symbols
    gc.collect()

    # The MT output bit sequence after the initial 624-word state has
    # characteristic polynomial degree 19937. Verify BM on two independent
    # concrete states/output bits before using polynomial skip-ahead.
    bm_length_1, connection_1 = berlekamp_massey(
        concrete_bit_stream(0x3912A, 31, 2 * DEGREE)
    )
    bm_length_2, connection_2 = berlekamp_massey(
        concrete_bit_stream(0x3912B, 16, 2 * DEGREE)
    )
    assert bm_length_1 == bm_length_2 == DEGREE
    assert connection_1 == connection_2
    modulus = reverse_bits(connection_1, DEGREE + 1)
    assert modulus.bit_length() - 1 == DEGREE
    assert modulus & 1
    square_table = make_square_table()

    # Three source-order schedules. N=2^18 is one 1-MiB chunk;
    # N=2^21 is eight unique 1-MiB chunks; N=2^22 is sixteen attempts.
    n18, n21, n22 = 1 << 18, 1 << 21, 1 << 22
    schedules = {
        "one_chunk_2^18": [
            ("AX-7781", 967 + n18),
            ("AX-7782", 983 + 2 * n18),
            ("AX-7783", 999 + 3 * n18),
        ],
        "eight_chunks_2^21": [
            ("AX-7781", 967 + n21),
            ("AX-7782", 983 + 2 * n21),
            ("AX-7783", 999 + 3 * n21),
        ],
        "sixteen_attempts_2^22": [
            ("AX-7781", 967 + n22),
            ("AX-7782", 983 + 2 * n22),
            ("AX-7783", 999 + 3 * n22),
        ],
        "dry_run_zero_then_8MiB": [
            ("AX-7781", 967),
            ("AX-7782", 983 + n21),
            ("AX-7783", 999 + 2 * n21),
        ],
    }

    starts_to_schedules = collections.defaultdict(list)
    for name, entries in schedules.items():
        for tag, start in entries:
            starts_to_schedules[start].append((name, tag))

    coefficients = {
        start: coefficients_for_burst(start, modulus, square_table)
        for start in starts_to_schedules
    }
    schedule_bases = {name: clone_basis(basis) for name in schedules}
    contradicted = {name: False for name in schedules}
    first_conflict = {name: None for name in schedules}
    stats = {
        name: {
            tag: {
                "fixed": 0,
                "matches": 0,
                "mismatches": 0,
                "fixed_by_checkpoint": [0] * 16,
            }
            for tag, _ in entries
        }
        for name, entries in schedules.items()
    }

    # A concrete high-index positive control checks the symbolic skip-ahead
    # against direct MT recurrence, at the first 2^21 schedule position.
    test_start = 967 + n21
    test_index = test_start + 476
    test_seed = 0x3912C
    test_rng = random.Random(test_seed)
    test_state = [test_rng.getrandbits(32) for _ in range(624)]
    test_state_bits = sum(word << (32 * i) for i, word in enumerate(test_state))
    positive_control_passed = False

    for bit in range(16, 32):
        forms = symbolic_output_bit_forms(bit)
        for start, entries in starts_to_schedules.items():
            for checkpoint_index, coefficient in enumerate(coefficients[start]):
                form = combine_form(forms, coefficient)
                source_prediction = basis.predict(form)
                for schedule_name, tag in entries:
                    actual = (values[tag][checkpoint_index] >> (bit - 16)) & 1
                    stat = stats[schedule_name][tag]
                    if source_prediction is not None:
                        stat["fixed"] += 1
                        stat["fixed_by_checkpoint"][checkpoint_index] += 1
                        if source_prediction == actual:
                            stat["matches"] += 1
                        else:
                            stat["mismatches"] += 1

                    if not contradicted[schedule_name]:
                        try:
                            schedule_bases[schedule_name].insert(form, actual)
                        except AssertionError:
                            contradicted[schedule_name] = True
                            first_conflict[schedule_name] = {
                                "transfer": tag,
                                "checkpoint_index": checkpoint_index,
                                "output_bit": bit,
                                "source_prediction": source_prediction,
                                "actual": actual,
                            }

                if bit == 31 and start == test_start and checkpoint_index == 0:
                    predicted = (form & test_state_bits).bit_count() & 1
                    actual_word = concrete_output_at(test_seed, test_index)
                    positive_control_passed = predicted == ((actual_word >> 31) & 1)
        del forms
        gc.collect()

    assert positive_control_passed

    summary = {}
    for name, entries in schedules.items():
        per_transfer = stats[name]
        fixed = sum(v["fixed"] for v in per_transfer.values())
        matches = sum(v["matches"] for v in per_transfer.values())
        mismatches = sum(v["mismatches"] for v in per_transfer.values())
        if contradicted[name]:
            rank_gain = None
            target_fixed = None
        else:
            rank_gain = schedule_bases[name].rank - basis.rank
            target_fixed = sum(
                schedule_bases[name].predict(form) is not None
                for form in target_forms
            )
        summary[name] = {
            "starts_by_transfer": {
                tag: start for tag, start in entries
            },
            "source_fixed_bits": fixed,
            "source_fixed_matches": matches,
            "source_fixed_mismatches": mismatches,
            "rank_gain_after_observations": rank_gain,
            "target_bits_fixed": target_fixed,
            "target_bits_unresolved": (
                None if target_fixed is None else 128 - target_fixed
            ),
            "contradicted": contradicted[name],
            "first_conflict": first_conflict[name],
            "per_transfer": per_transfer,
        }

    for name in ("one_chunk_2^18", "eight_chunks_2^21", "sixteen_attempts_2^22"):
        assert not summary[name]["contradicted"]
        assert summary[name]["source_fixed_bits"] == 0
        assert summary[name]["rank_gain_after_observations"] == 768
        assert summary[name]["target_bits_fixed"] == 0

    dry = summary["dry_run_zero_then_8MiB"]["per_transfer"]["AX-7781"]
    assert dry["fixed"] == 106
    assert dry["matches"] == 52
    assert dry["mismatches"] == 54
    assert summary["dry_run_zero_then_8MiB"]["contradicted"]

    print(json.dumps({
        "printer_basis_rank": 15365,
        "basis_rank_after_AX7778": basis.rank,
        "AX7778_rank_gain": 130,
        "AX7778_preinsert_fixed_bits": ax7778_preinsert_fixed,
        "base_target_bits_fixed": 0,
        "base_target_bits_unresolved": 128,
        "high_index_positive_control": positive_control_passed,
        "schedules": summary,
        "scope": (
            "Conditional MT19937 model only. A 32-bit MT output per four "
            "payload bytes is a hypothesis, not a fact established by the "
            "transfer records. Transfer IDs are tested in the queue-note "
            "order; per-chunk timestamps are absent."
        ),
    }, indent=2))


if __name__ == "__main__":
    main()

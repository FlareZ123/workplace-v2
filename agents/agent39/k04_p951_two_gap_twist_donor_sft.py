#!/usr/bin/env python3
"""Bounded source-block donor screen for the two p951 K04 twist gaps.

Run from the repository root:
    python agents/agent39/k04_p951_two_gap_twist_donor_sft.py

The script tests whether source-attested 16-byte blocks or intact printer
payloads can stand in for the two missing four-word MT blocks. It is not a
claim that those unrelated source fields were generated by the printer RNG.
"""
from __future__ import annotations

import collections
import hashlib
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "agents" / "agent49"))
sys.path.insert(0, str(ROOT / "work"))
import k04_p951_symbolic_basis as mt  # noqa: E402

MASK32 = 0xFFFFFFFF
MAG = 0x9908B0DF
K04_HASH = "930a52a1bab97ca2966332137c99e99298ea6182fb32ab63a3421dfb4fd8c9e0"


def undo_right(value: int, shift: int) -> int:
    out = value
    for _ in range(6):
        out = value ^ (out >> shift)
    return out & MASK32


def undo_left(value: int, shift: int, mask: int) -> int:
    out = value
    for _ in range(6):
        out = value ^ ((out << shift) & mask)
    return out & MASK32


def untemper(value: int) -> int:
    value = undo_right(value, 18)
    value = undo_left(value, 15, 0xEFC60000)
    value = undo_left(value, 7, 0x9D2C5680)
    value = undo_right(value, 11)
    return value & MASK32


def temper(value: int) -> int:
    value ^= value >> 11
    value ^= (value << 7) & 0x9D2C5680
    value ^= (value << 15) & 0xEFC60000
    value ^= value >> 18
    return value & MASK32


def twist_word(a: int, b: int) -> int:
    value = (((a & 0x80000000) | (b & 0x7FFFFFFF)) >> 1)
    if b & 1:
        value ^= MAG
    return value & MASK32


def mt_native_stream(seed: int, count: int) -> list[int]:
    rng = random.Random(seed)
    state = [rng.getrandbits(32) for _ in range(624)]
    output = []
    for i in range(count):
        a = state[i % 624]
        b = state[(i + 1) % 624]
        c = state[(i + 397) % 624]
        value = c ^ twist_word(a, b)
        value &= MASK32
        state[i % 624] = value
        output.append(value)
    return output


def source_block_variants(name: str, data: bytes):
    assert len(data) == 16, (name, len(data))
    out = []
    for endian in ("little", "big"):
        words = [
            int.from_bytes(data[i * 4:i * 4 + 4], endian)
            for i in range(4)
        ]
        out.append((f"{name}:{endian}:raw", words))
        out.append((f"{name}:{endian}:untemper",
                    [untemper(word) for word in words]))
    return out


def candidate_from_gap_blocks(a_words: list[int], b_words: list[int],
                              predecessor: int, mask: bytes):
    target_native = []
    for i in range(4):
        a0 = predecessor if i == 0 else a_words[i - 1]
        target_native.append(
            b_words[i] ^ twist_word(a0, a_words[i])
        )
    target_payload = b"".join(
        temper(word).to_bytes(4, "little") for word in target_native
    )
    component = bytes(x ^ y for x, y in zip(target_payload, mask))
    return component, hashlib.sha256(component).hexdigest(), target_payload


def main() -> None:
    evidence = ROOT / "resources" / "evidence"
    route = json.loads((evidence / "recovery-routing.json").read_text())
    acceptance = json.loads((ROOT / "acceptance.json").read_text())
    mask = bytes.fromhex(route["K04"]["masked_component"])
    nonce = bytes.fromhex(route["K08"]["desk_nonce"])
    assert hashlib.sha256(mask).hexdigest() != K04_HASH
    assert acceptance["slot_sha256"]["K04"] == K04_HASH

    # Assert the exact p951 stage geometry used by the two-gap relation.
    assert mt.STARTS[43] == 324
    assert mt.STARTS[96] == 717
    assert mt.STARTS[97] == 729
    assert mt.STARTS[129] == 951
    assert mt.STARTS[43] + 3 == 327
    assert 724 == 327 + 397
    assert 951 == 327 + 624

    spool = [
        line for line in
        (evidence / "print" / "spool-reconstruction.log").read_text().splitlines()
        if line.startswith("2026-")
    ]

    # Reproduce the two-gap information projection in the p951 source basis.
    audit_path = evidence / "transfers" / "transfer-audit.jsonl"
    audit_bytes = audit_path.read_bytes()
    assert hashlib.sha256(audit_bytes).hexdigest() == (
        "32970ad4431a9d610cc12dcca2813f39dd8fd2e396f9e748dc94b5932cb69adf"
    )
    audit_rows = [
        json.loads(line) for line in audit_bytes.splitlines() if line.strip()
    ]
    ax_rows = sorted(
        (row for row in audit_rows
         if row.get("kind") == "CHUNK" and row.get("transfer") == "AX-7778"),
        key=lambda row: (row["seq"], row["attempt"]),
    )
    assert len(ax_rows) == 16
    printer_basis, symbols = mt.source(ROOT)
    assert printer_basis.rank == 15365
    ax_preinsert_fixed = 0
    for index, row in enumerate(ax_rows):
        checkpoint = int.from_bytes(
            bytes.fromhex(row["checkpoint"]), "little"
        )
        forms = mt.temper(mt.get(symbols, -157 + index))
        for bit in range(16):
            form = forms[16 + bit]
            if printer_basis.predict(form) is not None:
                ax_preinsert_fixed += 1
            printer_basis.insert(form, (checkpoint >> bit) & 1)
    assert printer_basis.rank == 15495
    assert ax_preinsert_fixed == 126

    target_forms = [
        form for stage in range(951, 955)
        for form in mt.temper(mt.get(symbols, stage))
    ]
    block_a_forms = [
        form for stage in range(328, 332)
        for form in mt.temper(mt.get(symbols, stage))
    ]
    block_b_forms = [
        form for stage in range(724, 728)
        for form in mt.temper(mt.get(symbols, stage))
    ]

    def project_block_forms(forms):
        projected = mt.Basis()
        projected.rows = dict(printer_basis.rows)
        projected.rank = printer_basis.rank
        for form in forms:
            projected.insert(form, 0)
        return projected

    projected_a = project_block_forms(block_a_forms)
    projected_b = project_block_forms(block_b_forms)
    projected_ab = project_block_forms(block_a_forms + block_b_forms)
    two_gap_projection = {
        "printer_rank": 15365,
        "rank_after_AX7778": printer_basis.rank,
        "AX7778_preinsert_fixed_bits": ax_preinsert_fixed,
        "A_only_rank_gain": projected_a.rank - printer_basis.rank,
        "A_only_target_bits_fixed": sum(
            projected_a.predict(form) is not None for form in target_forms
        ),
        "B_only_rank_gain": projected_b.rank - printer_basis.rank,
        "B_only_target_bits_fixed": sum(
            projected_b.predict(form) is not None for form in target_forms
        ),
        "A_and_B_rank_gain": projected_ab.rank - printer_basis.rank,
        "A_and_B_target_bits_fixed": sum(
            projected_ab.predict(form) is not None for form in target_forms
        ),
    }
    assert two_gap_projection["A_only_rank_gain"] == 128
    assert two_gap_projection["A_only_target_bits_fixed"] == 0
    assert two_gap_projection["B_only_rank_gain"] == 128
    assert two_gap_projection["B_only_target_bits_fixed"] == 0
    assert two_gap_projection["A_and_B_rank_gain"] == 256
    assert two_gap_projection["A_and_B_target_bits_fixed"] == 128
    del symbols
    assert len(spool) == 133
    payload_match = re.search(r"PAYLOAD=([0-9A-F]{32})", spool[43])
    assert payload_match
    predecessor_payload = bytes.fromhex(payload_match.group(1))
    predecessor = untemper(
        int.from_bytes(predecessor_payload[12:16], "little")
    )

    # K01: signed WN-14 ink groups A,B,C,D.
    mail03 = (evidence / "mail" / "03.eml").read_text()
    mail06 = (evidence / "mail" / "06.eml").read_text()
    ink_groups = {}
    for match in re.finditer(
        r"WN-14 / group ([ABCD]) / ([0-9A-F]{8})", mail03 + "\n" + mail06
    ):
        ink_groups[match.group(1)] = match.group(2)
    assert set(ink_groups) == set("ABCD")
    k01_block = bytes.fromhex("".join(ink_groups[x] for x in "ABCD"))

    # K03: latest signed CLOSED/AS_LEFT PTW-417 serial for each bay A-D.
    seal_rows = [
        json.loads(line)
        for line in
        (evidence / "maintenance" / "seal-receipts.jsonl").read_text().splitlines()
        if line.strip()
    ]
    ptw = [row for row in seal_rows if row.get("permit") == "PTW-417"]
    latest = {}
    for bay in "ABCD":
        eligible = [
            row for row in ptw
            if row.get("bay") == bay
            and row.get("state") == "CLOSED"
            and row.get("fitment") == "AS_LEFT"
            and row.get("signed") is True
        ]
        assert eligible
        latest[bay] = max(eligible, key=lambda row: row["revision"])
    k03_block = bytes.fromhex("".join(
        latest[bay]["serial"].split("-")[1] for bay in "ABCD"
    ))

    # K06: revision-C footer strips in archive-label service order.
    labels = (evidence / "archive-labels.ini").read_text()
    order_match = re.search(r"service_order=([A-Z,]+)", labels)
    assert order_match
    service_order = order_match.group(1).split(",")
    assert service_order == ["DRAIN", "ISOLATE", "PURGE", "VERIFY"]
    rc17 = (evidence / "procedures" / "RC-17-scans.txt").read_text()
    strips = {}
    for match in re.finditer(
        r"DOCUMENT RC-17 / REV C / SECTION "
        r"(DRAIN|ISOLATE|PURGE|VERIFY).*?Footer control strip: ([0-9A-F]{8})",
        rc17,
        re.S,
    ):
        strips[match.group(1)] = match.group(2)
    assert set(strips) == set(service_order)
    k06_block = bytes.fromhex("".join(strips[name] for name in service_order))

    transfer_attempt_blocks = {}
    for transfer in ("AX-7778", "AX-7781", "AX-7782", "AX-7783"):
        for attempt in (1, 2):
            attempt_rows = sorted(
                (row for row in audit_rows
                 if row.get("kind") == "CHUNK"
                 and row.get("transfer") == transfer
                 and row.get("attempt") == attempt),
                key=lambda row: row["seq"],
            )
            assert len(attempt_rows) == 8
            assert [row["seq"] for row in attempt_rows] == list(range(8))
            packed = b"".join(
                int(row["checkpoint"], 16).to_bytes(2, "little")
                for row in attempt_rows
            )
            transfer_attempt_blocks[f"{transfer}_attempt{attempt}"] = packed

    external_blocks = {
        "K01_WN14_ABCD": k01_block,
        "K03_PTW417_ASLEFT_ABCD": k03_block,
        "K06_RC17_REV_C_SERVICE": k06_block,
        "K04_ROUTE_MASK": mask,
        "K08_DESK_NONCE": nonce,
        **transfer_attempt_blocks,
    }
    external_variants = [
        variant
        for name, block in external_blocks.items()
        for variant in source_block_variants(name, block)
    ]
    transfer_variants = [
        variant
        for name, block in transfer_attempt_blocks.items()
        for variant in source_block_variants(name, block)
    ]
    nontransfer_variants = [
        variant
        for name, block in external_blocks.items()
        if name not in transfer_attempt_blocks
        for variant in source_block_variants(name, block)
    ]

    external_tested = 0
    external_hits = []
    for name_a, block_a in external_blocks.items():
        for name_b, block_b in external_blocks.items():
            if name_a == name_b:
                continue
            for label_a, words_a in source_block_variants(name_a, block_a):
                for label_b, words_b in source_block_variants(name_b, block_b):
                    external_tested += 1
                    component, digest, payload = candidate_from_gap_blocks(
                        words_a, words_b, predecessor, mask
                    )
                    if digest == K04_HASH:
                        external_hits.append((label_a, label_b, component.hex()))

    same_external_tested = 0
    same_external_hits = []
    for name, block in external_blocks.items():
        block_variants = source_block_variants(name, block)
        for variant_a in block_variants:
            for variant_b in block_variants:
                same_external_tested += 1
                component, digest, payload = candidate_from_gap_blocks(
                    variant_a[1], variant_b[1], predecessor, mask
                )
                if digest == K04_HASH:
                    same_external_hits.append((
                        variant_a[0], variant_b[0], component.hex()
                    ))

    transfer_distinct_tested = 0
    transfer_distinct_hits = []
    for name_a, block_a in transfer_attempt_blocks.items():
        for name_b, block_b in transfer_attempt_blocks.items():
            if name_a == name_b:
                continue
            for label_a, words_a in source_block_variants(name_a, block_a):
                for label_b, words_b in source_block_variants(name_b, block_b):
                    transfer_distinct_tested += 1
                    component, digest, payload = candidate_from_gap_blocks(
                        words_a, words_b, predecessor, mask
                    )
                    if digest == K04_HASH:
                        transfer_distinct_hits.append(
                            (label_a, label_b, component.hex())
                        )

    transfer_same_tested = 0
    transfer_same_hits = []
    for name, block in transfer_attempt_blocks.items():
        variants = source_block_variants(name, block)
        for variant_a in variants:
            for variant_b in variants:
                transfer_same_tested += 1
                component, digest, payload = candidate_from_gap_blocks(
                    variant_a[1], variant_b[1], predecessor, mask
                )
                if digest == K04_HASH:
                    transfer_same_hits.append(
                        (variant_a[0], variant_b[0], component.hex())
                    )

    transfer_external_tested = 0
    transfer_external_hits = []
    for transfer_variant in transfer_variants:
        for other_variant in nontransfer_variants:
            for words_a, words_b in (
                (transfer_variant[1], other_variant[1]),
                (other_variant[1], transfer_variant[1]),
            ):
                transfer_external_tested += 1
                component, digest, payload = candidate_from_gap_blocks(
                    words_a, words_b, predecessor, mask
                )
                if digest == K04_HASH:
                    transfer_external_hits.append(
                        (transfer_variant[0], other_variant[0], component.hex())
                    )

    transfer_printer_tested = 0
    transfer_printer_hits = []
    for transfer_variant in transfer_variants:
        for printer_variant in printer_variants:
            for words_a, words_b in (
                (transfer_variant[1], printer_variant[3]),
                (printer_variant[3], transfer_variant[1]),
            ):
                transfer_printer_tested += 1
                component, digest, payload = candidate_from_gap_blocks(
                    words_a, words_b, predecessor, mask
                )
                if digest == K04_HASH:
                    transfer_printer_hits.append(
                        (transfer_variant[0], printer_variant[:3], component.hex())
                    )

    # All intact printer payloads except selected row 129 are also candidate
    # copied blocks. Try both per-word endiannesses and raw/untempered views.
    printer_blocks = []
    for index, line in enumerate(spool):
        if index == 129:
            continue
        match = re.search(r"PAYLOAD=([0-9A-F]{32})", line)
        assert match
        printer_blocks.append((index, bytes.fromhex(match.group(1))))
    assert len(printer_blocks) == 132

    printer_variants = []
    for row_index, block in printer_blocks:
        for endian in ("little", "big"):
            words = [
                int.from_bytes(block[i * 4:i * 4 + 4], endian)
                for i in range(4)
            ]
            printer_variants.append((row_index, endian, "raw", words))
            printer_variants.append((
                row_index, endian, "untemper", [untemper(word) for word in words]
            ))

    printer_tested = 0
    printer_hits = []
    for row_a, endian_a, view_a, words_a in printer_variants:
        for row_b, endian_b, view_b, words_b in printer_variants:
            if row_a == row_b:
                continue
            printer_tested += 1
            component, digest, payload = candidate_from_gap_blocks(
                words_a, words_b, predecessor, mask
            )
            if digest == K04_HASH:
                printer_hits.append((
                    row_a, endian_a, view_a,
                    row_b, endian_b, view_b, component.hex()
                ))

    same_row_tested = 0
    same_row_hits = []
    for row_index in range(133):
        row_variants = [v for v in printer_variants if v[0] == row_index]
        for variant_a in row_variants:
            for variant_b in row_variants:
                same_row_tested += 1
                component, digest, payload = candidate_from_gap_blocks(
                    variant_a[3], variant_b[3], predecessor, mask
                )
                if digest == K04_HASH:
                    same_row_hits.append((
                        variant_a[:3], variant_b[:3], component.hex()
                    ))

    cross_tested = 0
    cross_hits = []
    for printer_variant in printer_variants:
        for external_variant in external_variants:
            for words_a, words_b in (
                (printer_variant[3], external_variant[1]),
                (external_variant[1], printer_variant[3]),
            ):
                cross_tested += 1
                component, digest, payload = candidate_from_gap_blocks(
                    words_a, words_b, predecessor, mask
                )
                if digest == K04_HASH:
                    cross_hits.append((
                        printer_variant[:3], external_variant[0], component.hex()
                    ))

    # Positive control: the exact MT twist relation at t..t+627.
    synthetic = mt_native_stream(0x5A39, 327 + 624 + 4)
    positive_control = all(
        synthetic[327 + 624 + i]
        == (synthetic[327 + 397 + i]
            ^ twist_word(synthetic[327 + i], synthetic[327 + i + 1]))
        & MASK32
        for i in range(4)
    )
    assert positive_control

    assert external_tested == 2496
    assert same_external_tested == 208
    assert printer_tested == 276672
    assert same_row_tested == 2112
    assert cross_tested == 54912
    assert transfer_distinct_tested == 896
    assert transfer_same_tested == 128
    assert transfer_external_tested == 1280
    assert transfer_printer_tested == 33792

    summary = {
        "target_relation": (
            "x[951+i] = x[724+i] XOR twist(x[327+i], x[328+i]), i=0..3"
        ),
        "known_predecessor_stage": 327,
        "missing_A_block_stages": [328, 329, 330, 331],
        "missing_B_block_stages": [724, 725, 726, 727],
        "positive_control": positive_control,
        "two_gap_projection": two_gap_projection,
        "external_ordered_pair_candidates": external_tested,
        "external_hits": len(external_hits),
        "same_external_block_pair_candidates": same_external_tested,
        "transfer_attempt_pair_candidates": transfer_distinct_tested,
        "transfer_attempt_pair_hits": len(transfer_distinct_hits),
        "transfer_same_attempt_block_pair_candidates": transfer_same_tested,
        "transfer_same_attempt_block_pair_hits": len(transfer_same_hits),
        "transfer_external_cross_pair_candidates": transfer_external_tested,
        "transfer_external_cross_pair_hits": len(transfer_external_hits),
        "transfer_printer_cross_pair_candidates": transfer_printer_tested,
        "transfer_printer_cross_pair_hits": len(transfer_printer_hits),
        "same_external_block_pair_hits": len(same_external_hits),
        "distinct_printer_row_pair_candidates": printer_tested,
        "distinct_printer_row_pair_hits": len(printer_hits),
        "same_printer_row_pair_candidates": same_row_tested,
        "same_printer_row_pair_hits": len(same_row_hits),
        "printer_external_cross_pair_candidates": cross_tested,
        "printer_external_cross_pair_hits": len(cross_hits),
        "external_blocks": {name: block.hex()
                            for name, block in external_blocks.items()},
        "limitations": (
            "K02/K05/K07 halfword donor layouts are excluded because Agent 18 "
            "has already run the corresponding 64-case source screen. These "
            "tests only reject the listed raw-block reuse interpretations."
        ),
    }
    assert not external_hits
    assert not same_external_hits
    assert not transfer_distinct_hits
    assert not transfer_same_hits
    assert not transfer_external_hits
    assert not transfer_printer_hits
    assert not printer_hits
    assert not same_row_hits
    assert not cross_hits
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()

"""Constructive conditional non-identifiability of disputed original K04 coupon.

Two incompatible selected coupons can each be generated by an authentic CPython
624-word init_by_array seed while reproducing EVERY other intact printer record
under the published p955 MT chronology, with the entire selected row withheld.

The source-compatible chronology is a historically unauthenticated model.
No original K04 acceptance value, mask or final keeper inscription is read.
"""
import runpy
import random
from pathlib import Path

SOURCE = runpy.run_path(str(Path(__file__).with_name('k04_p955_seedseq_original_donors_sft.py')))
INTERNAL = SOURCE['basis_from'].__globals__
BASE, bad = SOURCE['basis_from']({129})
assert bad == 0 and len(BASE) == 15305
MASK = 0xFFFFFFFF


def original_state_with_coupon(target):
    piv = dict(BASE)

    def constrain(coeff, value):
        while coeff:
            k = coeff.bit_length()-1
            if k in piv:
                coeff ^= piv[k][0]
                value ^= piv[k][1]
            else:
                piv[k] = (coeff, value)
                return
        assert value == 0

    # The CPython init_by_array canonical state begins with this fixed word.
    for b in range(32):
        constrain(1 << b, (0x80000000 >> b) & 1)
    rank_after_initial_word = len(piv)

    # The disputed selected row is absent from the baseline system.
    for w, word in enumerate(target):
        for b, coeff in enumerate(SOURCE['temper'](SOURCE['state'][624+955+w])):
            constrain(coeff, (word >> b) & 1)
    assert rank_after_initial_word == 15336
    assert len(piv) == rank_after_initial_word+128

    solution = 0
    for k, (coeff, y) in sorted(piv.items()):
        bit = y ^ (((coeff ^ (1 << k)) & solution).bit_count() & 1)
        if bit:
            solution |= 1 << k
    state = [(solution >> (32*i)) & MASK for i in range(624)]
    assert state[0] == 0x80000000
    return state


def mulmix(value, multiplier):
    return ((value ^ (value >> 30))*multiplier) & MASK


def construct_624_word_seed(state):
    base = [19650218]
    for i in range(1,624):
        base.append((1812433253*(base[-1] ^ (base[-1] >> 30))+i)&MASK)

    # Invert CPython's second pass (i=2..623, then wrapped i=1).
    firstpass = [0]*624
    firstpass[1] = ((state[1]+1)&MASK) ^ mulmix(state[623],1566083941)
    firstpass[2] = ((state[2]+2)&MASK) ^ mulmix(firstpass[1],1566083941)
    for i in range(3,624):
        firstpass[i] = ((state[i]+i)&MASK) ^ mulmix(state[i-1],1566083941)

    # First pass i=1..623 and a second i=1. Choose the free seed word0
    # so the highest seed word is nonzero for EVERY possible state.
    key = [0]*624
    for first_seed_word in (0,1):
        key[0] = first_seed_word
        first_i1 = ((base[1] ^ mulmix(base[0],1664525)) +
                    first_seed_word) & MASK
        for i in range(2,624):
            preceding = first_i1 if i == 2 else firstpass[i-1]
            key[i-1] = (firstpass[i] -
                        (base[i] ^ mulmix(preceding,1664525)) -
                        (i-1)) & MASK
        key[623] = (firstpass[1] -
                    (first_i1 ^ mulmix(firstpass[623],1664525)) -
                    623) & MASK
        if key[623] != 0:
            break
    assert key[623] != 0
    seed = sum(word << (32*i) for i,word in enumerate(key))
    actual = list(random.Random(seed).getstate()[1][:624])
    assert actual == state
    return key


def original_printer_prediction(state, target):
    numbers = state[:]
    for k in range(max(INTERNAL['starts'])+4):
        y = (numbers[k]&0x80000000)|(numbers[k+1]&0x7FFFFFFF)
        numbers.append((numbers[k+397] ^ (y >> 1) ^
                        (0x9908B0DF if y & 1 else 0)) & MASK)

    def temper(x):
        x ^= x >> 11
        x ^= (x << 7) & 0x9D2C5680
        x ^= (x << 15) & 0xEFC60000
        return (x ^ (x >> 18)) & MASK

    for r in range(133):
        values = [temper(numbers[624+INTERNAL['starts'][r]+w]) for w in range(4)]
        if r == 129:
            assert values == target
        else:
            assert values == INTERNAL['rows'][r],r


